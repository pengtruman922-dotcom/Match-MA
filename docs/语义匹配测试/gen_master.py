def seg_text(rng: random.Random, key: str, thick: bool, use_alias: bool = False) -> str:
    """薄 = 一句话自述（80~140 字），不是残句；厚 = 年报摘要那样的一段（每单元 150+ 字）。

    第一版把薄组写成了 45 字，中位数只有 52 —— 那还是旧库的毛病换个说法。
    真实的「薄」是企业自己写的一句话简介，主营 + 一两个佐证，不会短到只剩主谓宾。
    """
    s = S[key]
    lead = s.get("alias") if (use_alias and s.get("alias")) else s["lead"]
    if not thick:
        parts = [lead + "。"]
        parts += [d + "。" for d in rng.sample(s["det"], k=rng.randint(2, len(s["det"])))]
        if rng.random() < 0.75:
            parts.append(s["down"] + "。")
        return "".join(parts)
    parts = [lead + "。"]
    dets = list(s["det"])
    rng.shuffle(dets)
    parts += [d + "。" for d in dets]           # 厚组把细节全铺开
    parts.append(s["down"] + "。")
    parts += detail_lines(rng, rng.randint(2, 3))
    return "".join(parts)


def compose(rng: random.Random, keys: list[str], thick: bool, multi_head: bool,
            use_alias: bool = False) -> str:
    """把若干业务单元拼成一段业务说明，厚组再掺入噪声。"""
    blocks = []
    for i, k in enumerate(keys):
        head = SEG_HEADS[i] if (multi_head and len(keys) > 1 and i < len(SEG_HEADS)) else ""
        blocks.append(head + seg_text(rng, k, thick, use_alias and i == 0))
    body = "".join(blocks)
    if thick:
        # 噪声是难点本身：认证、政策话术、产能规划、风险提示，对判断业务对不对口
        # 毫无帮助，却占了年报摘要一半的篇幅。模型要能从这些话里穿过去。
        noise = []
        for pool, p in ((NOISE_CERT, .8), (NOISE_OPS, .75),
                        (NOISE_POLICY, .55), (NOISE_RISK, .8), (NOISE_OUTLOOK, .6)):
            if rng.random() < p:
                noise.append(rng.choice(pool))
        rng.shuffle(noise)
        body += "".join(noise[:5])
    return body


def tags_for(rng: random.Random, keys: list[str]) -> list[str]:
    """标签是人工录入的：会滞后、会缺、偶尔会写错。模型必须自己决定信不信。"""
    all_tags: list[str] = []
    for k in keys:
        all_tags += S[k]["tags"]
    all_tags = list(dict.fromkeys(all_tags))
    r = rng.random()
    if r < 0.07:                      # 完全没录
        return []
    if r < 0.20 and len(keys) > 1:    # 只录了第一条腿，第二主业在标签里看不见
        return list(dict.fromkeys(S[keys[0]]["tags"]))
    if r < 0.25:                      # 录错：挂了个跟正文对不上的标签
        wrong = rng.choice([t for k in S for t in S[k]["tags"] if t not in all_tags])
        return all_tags[:1] + [wrong]
    return all_tags[:4]


def money(rng: random.Random) -> tuple[Any, Any]:
    """营收/净利，单位万元。留出一部分未录入 —— 真实库就是这样。"""
    if rng.random() < 0.18:
        return "", ""
    # 撮合库里的标的以中小企业为主：等权重会造出一堆百亿营收的工业软件公司，
    # 一眼假。按真实分布压到 0.3~10 亿为主，百亿级只留极少数。
    rev = int(rng.choices(
        [rng.randint(3000, 20000), rng.randint(20000, 80000),
         rng.randint(80000, 300000), rng.randint(300000, 900000)],
        weights=[42, 33, 19, 6])[0])
    if rng.random() < 0.12:
        return rev, ""
    margin = rng.choice([-0.08, -0.02, .02, .04, .06, .08, .11, .15, .2])
    return rev, int(rev * margin)


def listed(rng: random.Random) -> str:
    return rng.choices(["unlisted", "listed", "pre_ipo"], weights=[74, 18, 8])[0]


